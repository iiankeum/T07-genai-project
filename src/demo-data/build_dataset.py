def load_parts(folder: Path) -> dict:
    calls = {}
    for f in sorted(folder.glob("part_*.json")):
        for c in json.loads(f.read_text(encoding="utf-8"))["calls"]:
            if c["id"] in calls:
                raise SystemExit(f"중복 id {c['id']} ({f.name})")
            calls[c["id"]] = c
    return calls


