# 아이디어: AI 가상 소비자 패널

- 작성일: 2026-11-06
- 제안자 ID: iiankeum
- 타겟 업종/직무: 마케팅 / 광고·콘텐츠 마케터, 소상공인

광고 카피나 썸네일을 정할 때 대부분 팀 내부 감이나 상사 취향으로 결정한다. 실제 소비자 조사나 A/B 테스트는 돈과 시간이 들어서 작은 팀이나 소상공인은 엄두를 못 낸다.

광고 카피, 썸네일, 상세페이지를 올리면 LLM이 만든 다양한 가상 소비자(나이, 성별, 관심사, 소비 성향이 다른 페르소나 100명)가 각자 반응을 남긴다. 클릭할지, 왜 끌리는지 또는 왜 넘기는지를 모아 점수와 개선 포인트로 정리해준다.

- 입력 하나, 결과 하나로 아주 단순한 구조
- "광고 집행 전에 AI 소비자 100명한테 먼저 보여줬다"는 한 줄로 홍보가 가능함
- 시안 2~3개를 넣으면 가상 A/B 테스트처럼 비교 가능
- 우려포인트: AI 페르소나 반응이 실제 소비자와 얼마나 비슷한지 검증이 필요함. 공개된 실제 광고 성과 사례와 비교하는 방식으로 신뢰도를 보여줘야 함
